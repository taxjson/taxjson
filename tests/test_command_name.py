"""The command is `tjs` in everything people read: `taxjson run` in a
message, a usage line, a report or a doc mixes two names for one program.
`taxjson` stays the project's name (taxjson.toml, the package, `taxjson-*`,
TAXJSON_*) and still runs the same program.

Synthetic data only.
"""
import contextlib
import io
import re
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TOP_FILES = ("README.md", "SECURITY.md", "CONTRIBUTING.md", "REFERENCES.md",
             "AGENTS.md", "install.sh")
FOLDERS = ("src", "packages", "docs", "examples", ".github")
SUFFIXES = {".py", ".md", ".sh", ".toml", ".html", ".txt", ".yml"}
# Bytes kept as they are because a file written by an earlier release is
# matched against them or hashed: not text for people.
STORED = re.compile(r'GENERATED_MARK\s*=|"# taxjson run:|EFFECTIVE_HEAD\s*=')
# "the taxjson gains engine": the project's gains, not the command.
PROSE = re.compile(r"taxjson gains (?:engine|into)|not a taxjson gains")


def _commands():
    from taxjson.bin.taxjson_run import _build_parser
    _p, sub = _build_parser()
    return sorted(sub.choices, key=len, reverse=True)


def _files():
    for name in TOP_FILES:
        yield REPO_ROOT / name
    for folder in FOLDERS:
        for p in (REPO_ROOT / folder).rglob("*"):
            if p.is_file() and p.suffix in SUFFIXES:
                yield p


class TestCommandName(unittest.TestCase):
    def test_no_text_names_the_command_taxjson(self):
        cmds = "|".join(map(re.escape, _commands()))
        self.assertGreater(len(cmds), 200)
        # Across a wrapped line and a string literal broken in two as well.
        gap = (r"""(?:[ \t]+|[ \t]*\n[ \t]*(?:\#[ \t]*|//[ \t]*|>[ \t]*)?"""
               r"""|[ ]?["'][ \t]*\n[ \t]*(?:rb|fr|rf|f|r|b)?["'][ ]?)""")
        rx = re.compile(rf"(?<![\w./-])taxjson{gap}"
                        rf"(?:(?:{cmds})(?![\w-])|-C\b|--help\b|<command>)")
        found = []
        for p in _files():
            text = p.read_text(encoding="utf-8", errors="replace")
            for m in rx.finditer(text):
                start = text.rfind("\n", 0, m.start()) + 1
                end = text.find("\n", m.end())
                line = text[start:end if end >= 0 else len(text)]
                if not (STORED.search(line) or PROSE.search(line)):
                    n = text.count("\n", 0, m.start()) + 1
                    found.append(f"{p.relative_to(REPO_ROOT)}:{n}: "
                                 f"{line.strip()[:80]}")
        self.assertEqual(found, [], "say `tjs <command>`")

    def test_every_stored_marker_is_still_read(self):
        # What keeps the old name on purpose, until no file of it is left.
        mark = (REPO_ROOT / "src/taxjson/lib/crypto_sends.py").read_text(
            encoding="utf-8")
        self.assertIn('"# GENERATED by `taxjson crypto-sends --write`', mark)

    def test_version_output_keeps_the_projects_name(self):
        # `deploy` compares it with this exact text; old installs print it.
        from taxjson.bin.taxjson_run import _build_parser
        text = (REPO_ROOT / "src/taxjson/lib/channels.py").read_text(
            encoding="utf-8")
        self.assertIn('if got != f"taxjson {want[1:]}":', text)
        parser, _sub = _build_parser()
        with self.assertRaises(SystemExit), \
                contextlib.redirect_stdout(io.StringIO()) as out:
            parser.parse_args(["--version"])
        self.assertRegex(out.getvalue(), r"^taxjson \S+")

    def test_both_names_run_the_program(self):
        text = (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8")
        target = "taxjson.bin.taxjson_run:main"
        self.assertIn(f'tjs = "{target}"', text)
        self.assertIn(f'taxjson = "{target}"', text)


class TestFilesWrittenBeforeTheChange(unittest.TestCase):
    """Written by the release before: their comments are template text,
    never kept as the user's notes (the retired lines are known by hash)."""

    def test_taxjson_toml(self):
        from taxjson.lib.config_template import format_config
        for country in ("canada", "usa"):
            old = (REPO_ROOT / "tests/fixtures/config_template"
                   / f"before_tjs_{country}.toml").read_text(encoding="utf-8")
            self.assertIn("`taxjson format`", old)
            r = format_config(old)
            self.assertEqual((r.notes_lines, r.kept_comments), (0, 0), r.text)
            self.assertNotIn("`taxjson format`", r.text)
            self.assertFalse(format_config(r.text).changed)

    def test_ticker_map(self):
        from taxjson.lib.ticker_map_format import format_map
        old = (REPO_ROOT / "tests/fixtures/ticker_map/before_tjs.map"
               ).read_text(encoding="utf-8")
        self.assertIn("`taxjson format-map`", old)
        r = format_map(old)
        self.assertNotIn("`taxjson format-map`", r.text)
        self.assertIn("GLOBAL ZZA.US ZZB.US", r.text)
        self.assertEqual(r.edited_headers, [])
        self.assertFalse(format_map(r.text).changed)


class TestCompareReadsTheOldName(unittest.TestCase):
    def test_a_report_of_either_name_compares_the_same(self):
        from taxjson.lib.compare import normalized
        old = b"Run `taxjson list` (taxjson run: warning) 12.50\n"
        new = b"Run `tjs list` (tjs run: warning) 12.50\n"
        self.assertEqual(normalized(old), normalized(new))

    def test_a_figure_or_a_file_name_is_not_touched(self):
        from taxjson.lib.compare import normalized
        self.assertNotEqual(normalized(b"taxjson list 12.50\n"),
                            normalized(b"tjs list 12.51\n"))
        self.assertIn("taxjson.toml", normalized(b"see taxjson.toml\n"))
        self.assertIn("taxjson-gains x", normalized(b"taxjson-gains x\n"))


if __name__ == "__main__":
    unittest.main()
