def _fetch_epilog() -> str:
    """`tjs fetch --help`'s last lines: the loaded fetchers, then each one
    of another version, not loaded (backlog TJ-2554); else the install."""
    from taxjson.lib import fetchers as _FP
    loaded = "; ".join(f"{f.name} ({', '.join(f.brokerages)})"
                       for f in _FP.installed())
    stale = [f"{m}." for m in _FP.mismatched()]
    if not loaded:
        return " ".join(stale) or f"No fetcher is installed: {_FP.INSTALL_HINT}."
    return " ".join([f"Installed fetchers: {loaded}.", *stale]) if stale \
        else f"Installed fetchers: {loaded}"


def _register_fetch(sub: argparse._SubParsersAction) -> None:
    p_fetch = sub.add_parser(
        "fetch",
        help="Download broker activity (taxjson-fetch plugin)",
        description="Download broker activity straight into inputs/ "
                    "through an installed fetcher plugin (taxjson-fetch: "
                    "Questrade REST API, IBKR Flex Web Service), "
                    "configured by `brokerage` under [accounts.<name>]. "
                    "Writes files the existing parsers read; "
                    "hand-exported CSVs keep working side by side.",
        conflict_handler="resolve")
    p_fetch.add_argument("account", nargs="*",
                         metavar="ACCOUNT[,ACCOUNT...]",
                         help="Accounts to fetch, space-separated or as "
                              "a comma list (default: every account "
                              "declaring a `brokerage`)")
    p_fetch.add_argument("--list", action="store_true",
                         help="List the installed fetchers and the "
                              "brokerages each one serves")
    p_fetch.add_argument("--fetcher", metavar="NAME", default=None,
                         help="Use only this installed fetcher "
                              "(default: each account's brokerage "
                              "picks it)")
    p_fetch.add_argument("--json", action="store_true",
                         help="Emit a machine-readable summary "
                              "(files, windows, rows added, activity "
                              "types, overlaps); progress moves to "
                              "stderr")
    p_fetch.add_argument("--dry-run", action="store_true",
                         help="Show what would be written without "
                              "touching inputs/")
    # The fetchers' own options (taxjson-fetch: --year, --days, --from,
    # --refresh-token, --flex-token, --positions, --trim-overlap) come
    # from the installed plugins — looked up only when `fetch` is on
    # the command line, so no other command pays for the scan.
    if "fetch" in sys.argv[1:]:
        from taxjson.lib import fetchers as _FP
        _FP.add_fetcher_arguments(p_fetch)
        p_fetch.epilog = _fetch_epilog()
    p_fetch.set_defaults(func=cmd_fetch, account_list=True)


