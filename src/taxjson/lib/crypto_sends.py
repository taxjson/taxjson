def tt_entries(acct_doc: Dict[str, Any]) -> Tuple[List[Dict[str, Any]],
                                                  List[Dict[str, Any]]]:
    """(entries to write, entries that cannot be priced): every
    gift/payment send and every network fee hidden in a matched send
    (``network_fees``). A decision the country refuses (``refused``) is
    never written. Each priced entry is written on its own: one that
    cannot be priced no longer holds back the rest (re-audit A2-0240)."""
    todo = [e for e in acct_doc["sends"]
            if e["decision"] in DISPOSING and not e["stable"]
            and not e.get("refused")]
    todo += list(acct_doc.get("network_fees") or [])
    return ([e for e in todo if e["tt"]], [e for e in todo if not e["tt"]])


def tt_want_ids(acct_doc: Dict[str, Any]) -> set:
    """The ids a current crypto_sends.tt records (the checklist's
    staleness check; no prices needed)."""
    return ({e["id"] for e in acct_doc["sends"]
             if e["decision"] in DISPOSING and not e["stable"]
             and not e.get("refused")}
            | {e["id"] for e in acct_doc.get("network_fees") or []})


def refused_entries(acct_doc: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Saved decisions the project's country refuses (a US gift)."""
    return [e for e in acct_doc["sends"] if e.get("refused")]


def render_tt(account: str, entries: List[Dict[str, Any]],
              country: str = "canada") -> Optional[str]:
    if not entries:
        return None
    from taxjson.lib.country import canonical_country
    if canonical_country(country) == "usa":
        why = ["# Each line is a crypto send that left your ownership as a "
               "payment: a sale at",
               "# fair market value (a gift is not a sale for a US donor "
               "and is never written)."]
    else:
        why = ["# Each line is a crypto send that left your ownership: a "
               "gift or a payment is a",
               "# disposition at fair market value (a gift: ITA "
               "s.69(1)(b))."]
    if any(e.get("network_fee") for e in entries):
        why += ["# A `-fee` line is the network fee hidden in a send that "
                "arrived short on",
                "# another of your exchanges: the coins that did not "
                "arrive paid for a service,",
                "# a sale at fair value (as a Kraken withdrawal fee "
                "paid in the coin is)."]
    out = [GENERATED_MARK,
           f"# Source: inputs/{account}/{MANIFEST_NAME} (your decisions) — "
           f"`taxjson crypto-sends {account}` lists them.",
           *why,
           ""]
    for e in sorted(entries, key=lambda e: (e["date"], e["time"], e["id"])):
        if e.get("network_fee"):
            ex = _EXCH_NAME.get(e["exchange"], e["exchange"])
            out.append(f"# {e['id']}: network fee — {ex} {e['kind']} "
                       f"{e['date']} {e['time']} of {fmt_qty(e['sent'])} "
                       f"{e['symbol']}, {fmt_qty(e['arrived'])} arrived on "
                       f"{e['arrived_on']}")
            out.append(f"#   fair value {fmt_price(e['fair_value']['price'])} "
                       f"{e['fair_value'].get('currency', '')} per "
                       f"{e['symbol']}: {e['fair_value']['source']}")
            out.append(e["tt"])
            continue
        what = {"gift": "gift", "payment": "payment"}[e["decision"]]
        ex = _EXCH_NAME.get(e["exchange"], e["exchange"])
        out.append(f"# {e['id']}: {what} — {ex} {e['kind']} {e['date']} "
                   f"{e['time']} of {fmt_qty(e['quantity'])} {e['symbol']}")
        if e["fee_booked"]:
            out.append(f"#   the {fmt_qty(e['fee_booked'])} {e['symbol']} "
                       f"network fee is already booked from the ledger")
        out.append(f"#   fair value {fmt_price(e['fair_value']['price'])} "
                   f"{e['fair_value'].get('currency', '')} per "
                   f"{e['symbol']}: {e['fair_value']['source']}")
        if e.get("note"):
            out.append(f"#   note: {' '.join(str(e['note']).split())}")
        out.append(e["tt"])
    return "\n".join(out) + "\n"


def write_tt(path: Path, text: Optional[str]) -> str:
    """'written' | 'unchanged' | 'removed' | 'absent'. Refuses to touch
    a crypto_sends.tt it did not generate."""
    exists = path.is_file()
    if exists:
        cur = path.read_text(encoding="utf-8")
        if not cur.startswith(GENERATED_MARK):
            raise ValueError(
                f"{path} exists but was not generated by `taxjson "
                f"crypto-sends` — refusing to overwrite it. Rename it "
                f"(any other .tt name works) and re-run.")
        if text == cur:
            return "unchanged"
        if text is None:
            path.unlink()
            return "removed"
    elif text is None:
        return "absent"
    tmp = path.with_name(path.name + ".part")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
    return "written"


def tt_ids(path: Path) -> Optional[set]:
    """Send ids recorded in a generated crypto_sends.tt (None: no file)."""
    if not path.is_file():
        return None
    ids = set()
    for ln in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^# ((?:kr|cb|[a-z]{2})-\d{8}T\d{6}-\S+): ", ln)
        if m:
            ids.add(m.group(1))
    return ids


def tt_stale_ids(acct_doc: Dict[str, Any], path: Path) -> List[str]:
    """Ids whose generated line in crypto_sends.tt is not the one the
    saved decision gives now: the id is missing or extra, or — when the
    fair value is known offline (a --price, the cached rates) — its
    BUYSELL line differs (a changed --price left the old sale booked
    while the id-only check said current, A2-1151)."""
    want = tt_want_ids(acct_doc)
    have = tt_ids(path) or set()
    stale = set(want ^ have)
    try:
        lines = set(path.read_text(encoding="utf-8").splitlines()) \
            if path.is_file() else set()
    except OSError:
        lines = set()
    for e in list(acct_doc["sends"]) + list(acct_doc.get("network_fees") or []):
        if e["id"] in want and e.get("tt") and e["tt"] not in lines:
            stale.add(e["id"])
    return sorted(stale)


def disposing_entries(acct_doc: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Every send crypto_sends.tt sells (priced or not): the decided
    gifts/payments and the network fees — what a hand-written .tt line
    must not sell again (duplicate_lines)."""
    return ([e for e in acct_doc["sends"]
             if e["decision"] in DISPOSING and not e["stable"]
             and not e.get("refused")]
            + list(acct_doc.get("network_fees") or []))


# A hand-written quantity this close to a generated one sells the same
# coins: a network fee folded in (-1000.01 for 1000), or the ledger
# quantity rounded (re-audit A2-0575 / A2-1005).
DUP_REL_TOL = 0.005


def _hand_qty_close(tok: str, q: float, want: float) -> bool:
    """Whether hand-written quantity `q` (token `tok`) is `want`."""
    frac = tok.lstrip("+-").replace(",", "").split(".")
    half_ulp = 0.5 * 10 ** -len(frac[1]) if len(frac) > 1 else 0.5
    return abs(q - want) <= max(want * DUP_REL_TOL, half_ulp) + 1e-12


def duplicate_lines(acct_dir: Path, entries: List[Dict[str, Any]]
                    ) -> List[Dict[str, Any]]:
    """Hand-written .tt lines that already sell what a generated
    crypto_sends.tt line sells — the same coin and about the same
    quantity (within DUP_REL_TOL, or the hand line's rounding) on the
    send's local date or the day either side (a hand line dated by the
    UTC stamp), on one line or split over several lines of one file —
    so booking both counts the disposition twice. Numbers are read the
    way convert-tt reads them ('-1,000' is 1000). Every account's
    folder under inputs/ is searched (one pool per coin across accounts
    in Canada). Each hit: {"file": path relative to the project,
    "line": 1-based, "id": send id, "timestamp": the send's date and
    time, "same_time": the .tt line has the send's exact time}. Nothing
    is deleted: which line to keep is the owner's call."""
    from taxjson.bin.taxjson_convert_tt import _tt_num
    hits: List[Dict[str, Any]] = []
    inputs = acct_dir.parent
    if not inputs.is_dir() or not entries:
        return hits

    def near(d1: str, d2: str) -> bool:
        try:
            a = datetime.strptime(d1, "%Y-%m-%d")
            b = datetime.strptime(d2, "%Y-%m-%d")
        except ValueError:
            return False
        return abs((a - b).days) <= 1

    for d in sorted(p for p in inputs.iterdir() if p.is_dir()):
        for p in sorted(d.iterdir()):
            if (not p.is_file() or p.suffix.lower() != ".tt"
                    or p.name == TT_NAME):
                continue
            try:
                text = p.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            lines = []
            for n, ln in enumerate(text.splitlines(), 1):
                tok = ln.split("#", 1)[0].split()
                if len(tok) < 5 or tok[0].upper() != "BUYSELL":
                    continue
                try:
                    q = _tt_num(tok[4])
                except ValueError:
                    continue
                if q < 0:
                    lines.append((n, tok, -q))
            for e in entries:
                sym = e["symbol"].upper()
                cand = [(n, tok, q) for n, tok, q in lines
                        if tok[3].upper() == sym and near(tok[1], e["date"])]
                found = [c for c in cand
                         if _hand_qty_close(c[1][4], c[2], e["quantity"])]
                if not found and len(cand) > 1:
                    tot = sum(q for _n, _t, q in cand)
                    if abs(tot - e["quantity"]) <= (e["quantity"]
                                                    * DUP_REL_TOL + 1e-12):
                        found = cand
                for n, tok, _q in found:
                    hits.append({
                        "file": f"{inputs.name}/{d.name}/{p.name}",
                        "line": n, "id": e["id"],
                        "timestamp": f"{e['date']} {e['time']}",
                        "same_time": (tok[1] == e["date"]
                                      and tok[2] == e["time"]),
                        "quantity": e["quantity"],
                        "symbol": e["symbol"]})
    return hits


