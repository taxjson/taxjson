_ANSWERS = {"s": "self", "self": "self", "g": "gift", "gift": "gift",
            "p": "payment", "payment": "payment", "k": None, "skip": None,
            "": None}


def prompt_undecided(sends: List[Dict[str, Any]], manifest: Path,
                     ask: Callable[[str], str] = input,
                     say: Callable[[str], None] = None,
                     allow_gift: bool = True) -> int:
    """Ask once per undecided send; save each answer as it is given.
    Returns the number of decisions recorded."""
    if say is None:
        def say(msg: str) -> None:
            print(msg, file=sys.stderr)
    todo = [s for s in sends if not s.get("decision")]
    if not todo:
        return 0
    say(f"  {len(todo)} crypto send(s) left an exchange and did not "
        f"arrive on another one. For each: self = your own wallet (no "
        f"tax event); "
        + ("gift / payment = a disposition at fair value; " if allow_gift
           else "payment = a sale at fair value (a gift is not a sale "
                "for a US donor: answer self); ")
        + "skip = decide later (`taxjson crypto-sends`).")
    done = 0
    for s in todo:
        say(f"  {s['id']}  {s['summary']}")
        fv = s.get("fair_value")
        if fv:
            cur = fv.get("currency", "")
            say(f"      fair value {fmt_price(fv['price'])} {cur} per "
                f"{s.get('symbol', '')} = {fv['value']:.2f} {cur} "
                f"[{fv['source']}]")
        if s.get("stable"):
            fx = s.get("fx")
            say("      stablecoin (US-dollar cash in the books): a gift "
                "or payment is a currency disposition — no sale line"
                + (f"; FX gain {fx['gain']:+.2f}"
                   + (" (likely superficial)" if fx.get("superficial")
                      else "") if fx else ""))
        while True:
            try:
                raw = ask("      [s]elf / [g]ift / [p]ayment / s[k]ip? "
                          if allow_gift else
                          "      [s]elf / [p]ayment / s[k]ip? ")
            except EOFError:
                return done
            ans = (raw or "").strip().lower()
            if ans not in _ANSWERS:
                say("      answer s, g, p or k")
                continue
            dec = _ANSWERS[ans]
            if dec == "gift" and not allow_gift:
                say("      US: a gift is not a sale for the donor — "
                    "answer self or payment")
                continue
            break
        if dec:
            record_decision(manifest, s["id"], dec, summary=s["summary"])
            done += 1
    return done
